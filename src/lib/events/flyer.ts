/** The description's first sentence (cut at the first . ! or ? followed by a space), or a word-boundary cut with "…". */
export function firstSentence(desc: string | null | undefined, max = 160): string {
  const text = (desc ?? "").replace(/\s+/g, " ").trim();
  if (!text) return "";
  const m = /[.!?](?=\s)/.exec(text);
  if (m && m.index + 1 <= max) return text.slice(0, m.index + 1);
  if (flyerTextLength(text) <= max) return text;
  const chars = Array.from(text).slice(0, Math.max(1, max - 1)).join("");
  const space = chars.lastIndexOf(" ");
  const cut = (space > max * 0.4 ? chars.slice(0, space) : chars).replace(/[\s,;:–—-]+$/, "");
  return `${cut}…`;
}

/** "Sat, Nov 8 · 6:00 PM–9:00 PM" in the community's time zone; "" without a start. */
export function flyerDateLine(startsAt: string | null | undefined, endsAt: string | null | undefined, tz: string, now: Date = new Date()): string {
  if (!startsAt || Number.isNaN(Date.parse(startsAt))) return "";
  const range = formatEventRange(startsAt, endsAt, tz, now);
  const end = endsAt && !Number.isNaN(Date.parse(endsAt)) ? formatTime(endsAt, tz) : null;
  return `${range} · ${formatTime(startsAt, tz)}${end ? `–${end}` : ""}`;
}

/** The pattern that suits an event, from its name. */
export function artMotifFor(name: string): FlyerPattern {
  const n = name.toLowerCase();
  if (/\bdiwali\b/.test(n)) return "diya";
  if (/\b(?:paryushan|samvatsari)/.test(n)) return "lotus";
  if (/\bnavratri\b/.test(n)) return "rangoli";
  return "mandala";
}

function cut(s: string, max: number): string {
  const chars = Array.from(s.replace(/\s+/g, " ").trim());
  return chars.length <= max ? chars.join("") : chars.slice(0, max).join("").trim();
}

/** "5:00 PM" and "9:00 PM" of one day → "5:00–9:00 PM" (AM or PM written once when both are in the same half of the day). */
function timeRange(start: string, end: string): string {
  const a = /^(.*)\s([AP]M)$/i.exec(start);
  const b = /^(.*)\s([AP]M)$/i.exec(end);
  return a && b && a[2].toUpperCase() === b[2].toUpperCase() ? `${a[1]}–${b[1]} ${b[2]}` : `${start}–${end}`;
}

/** An event that ends after midnight but within this many hours of its start is one evening (a Garba night), not two days. */
const ONE_EVENING_HOURS = 14;

/**
 * The ribbon's two lines in the community's time zone, from the event's start and end:
 *   no end (or an end that is not after the start)   "Saturday, October 3, 2026" / "5:00 PM onwards"
 *   one day                                         "Saturday, October 3, 2026" / "5:00–8:30 PM"
 *   one evening that runs past midnight             "Friday, October 16, 2026" / "7:00 PM–12:30 AM"
 *   several days                                    "September 10–16, 2026" / "6:00 PM onwards"
 * For several days the event records only the first day's start and the last day's end, so the time line gives
 * the start and nothing it cannot know (no "each day" and no end time). Empty without a start.
 */
export function posterWhen(startsAt: string | null | undefined, endsAt: string | null | undefined, tz: string): { date: string; time: string } {
  if (!startsAt || Number.isNaN(Date.parse(startsAt))) return { date: "", time: "" };
  const startMs = Date.parse(startsAt);
  const endMs = endsAt && !Number.isNaN(Date.parse(endsAt)) && Date.parse(endsAt) > startMs ? Date.parse(endsAt) : null;
  const parts = (ms: number) =>
    Object.fromEntries(
      new Intl.DateTimeFormat("en-US", { timeZone: tz, weekday: "long", year: "numeric", month: "long", day: "numeric" })
        .formatToParts(new Date(ms))
        .map((p) => [p.type, p.value]),
    ) as Record<string, string>;
  const clock = (ms: number) => formatTime(new Date(ms).toISOString(), tz).replace(/[\u00A0\u202F]/g, " ");
  const s = parts(startMs);
  const startDate = `${s.weekday}, ${s.month} ${s.day}, ${s.year}`;
  const onwards = `${clock(startMs)} onwards`;
  if (endMs === null) return { date: startDate, time: onwards };
  const e = parts(endMs);
  if (s.year === e.year && s.month === e.month && s.day === e.day) return { date: startDate, time: timeRange(clock(startMs), clock(endMs)) };
  if (endMs - startMs <= ONE_EVENING_HOURS * 3_600_000) return { date: startDate, time: `${clock(startMs)}–${clock(endMs)}` };
  const date =
    s.year !== e.year
      ? `${s.month} ${s.day}, ${s.year} – ${e.month} ${e.day}, ${e.year}`
      : s.month === e.month
        ? `${s.month} ${s.day}–${e.day}, ${s.year}`
        : `${s.month} ${s.day} – ${e.month} ${e.day}, ${s.year}`;
  return { date, time: onwards };
}

/** The description, cut at a sentence end (or a word) to fit `max` characters. */
function paragraphFrom(desc: string | null | undefined, max: number): string {
  const text = (desc ?? "").replace(/\s+/g, " ").trim();
  if (flyerTextLength(text) <= max) return text;
  const chars = Array.from(text).slice(0, max).join("");
  const end = Math.max(chars.lastIndexOf(". "), chars.lastIndexOf("! "), chars.lastIndexOf("? "));
  if (end > max * 0.5) return chars.slice(0, end + 1);
  return firstSentence(text, max);
}

/** A new poster for an event: its own words and date, the pack that suits its name, every optional section ready to fill. */
export function defaultPoster(e: { name: string; description: string | null; startsAt: string | null; endsAt: string | null; tz: string }): PosterContent {
  const when = posterWhen(e.startsAt, e.endsAt, e.tz);
  return {
    occasion: occasionFor(e.name, e.description),
    frame: { source: "code" },
    scene: { source: "code" },
    logo: true,
    partner: { on: false, label: "", sub: "", logo_path: null },
    subhead: "",
    slogan: "",
    stat: { on: false, icon: "people", label: "", value: "", caption: "" },
    ribbon: { on: true, date: cut(when.date, POSTER_LIMITS.ribbon_date), time: cut(when.time, POSTER_LIMITS.ribbon_time) },
    agenda: [],
    paragraph: cut(paragraphFrom(e.description, POSTER_LIMITS.paragraph), POSTER_LIMITS.paragraph),
    footer: "",
  };
}

