export const FLYER_LIMITS = { headline: 90, tagline: 180, date_line: 90, venue_line: 120 } as const;
const FIELD_LABEL: Record<keyof typeof FLYER_LIMITS, string> = {
  headline: "headline",
  tagline: "tagline",
  date_line: "date line",
  venue_line: "venue line",
};

/** Characters as a person counts them (code points, so a Gujarati letter with its sign counts per symbol, not per UTF-16 unit). */
export function flyerTextLength(s: string): number {
  return Array.from(s).length;
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const ART_PATH = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\/events\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\/art-\d{1,16}\.(?:jpg|png)$/i;

/** Is this the storage key of THIS event's AI background art (content/<center>/events/<event>/art-<ms>.<jpg|png>)? */
export function isFlyerArtPath(path: string, centerId: string, eventId: string): boolean {
  return ART_PATH.test(path) && path.toLowerCase().startsWith(`${centerId}/events/${eventId}/art-`.toLowerCase());
}

function cleanLine(v: unknown): string {
  // Control characters (tabs, line breaks) and no-break spaces (a time such as "5:00 PM" may carry one) become
  // spaces: the flyer lays out its own lines, and a font may not have the glyph.
  return typeof v === "string" ? v.replace(/[\u0000-\u001F\u007F\u00A0\u202F]+/g, " ").replace(/ {2,}/g, " ").trim() : "";
}

const PARTNER_LOGO = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\/events\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\/partner-\d{1,16}\.(?:jpg|png)$/i;

/** Is this the storage key of THIS event's partner logo (content/<center>/events/<event>/partner-<ms>.<jpg|png>)? */
export function isPartnerLogoPath(path: string, centerId: string, eventId: string): boolean {
  return PARTNER_LOGO.test(path) && path.toLowerCase().startsWith(`${centerId}/events/${eventId}/partner-`.toLowerCase());
}

function parseLayer(raw: unknown, kind: "frame" | "scene", occasion: FlyerOccasion): { ok: true; value: FlyerLayer } | { ok: false; error: string } {
  const o = raw && typeof raw === "object" && !Array.isArray(raw) ? (raw as Record<string, unknown>) : null;
  const what = kind === "frame" ? "frame" : "bottom scene";
  if (!o || o.source === "code") return { ok: true, value: { source: "code" } };
  if (o.source === "none") return { ok: true, value: { source: "none" } };
  if (o.source === "ai") {
    const path = typeof o.path === "string" ? o.path.trim() : "";
    const parsed = parseFlyerArtPath(path);
    if (!parsed || parsed.layer !== kind) return { ok: false, error: `The AI ${what} is not one the flyer maker made. Choose it again, or use the drawn ${what}.` };
    if (parsed.occasion !== occasion) return { ok: false, error: `The AI ${what} was made for another occasion. Choose one made for this occasion, or use the drawn ${what}.` };
    return { ok: true, value: { source: "ai", path } };
  }
  return { ok: false, error: `Choose a ${what}: the drawn one, AI art, or none.` };
}

/** The Poster's content, checked; every error is a plain sentence for the organizer. */
export function parsePosterContent(raw: unknown): { ok: true; poster: PosterContent } | { ok: false; error: string } {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return { ok: false, error: "The poster's content is missing. Reload the page and try again." };
  const o = raw as Record<string, unknown>;
  const obj = (v: unknown) => (v && typeof v === "object" && !Array.isArray(v) ? (v as Record<string, unknown>) : {});
  if (!isFlyerOccasion(o.occasion)) return { ok: false, error: "Choose an occasion for the poster's art." };
  const occasion = o.occasion;
  const frame = parseLayer(o.frame, "frame", occasion);
  if (!frame.ok) return frame;
  const scene = parseLayer(o.scene, "scene", occasion);
  if (!scene.ok) return scene;
  const partner = obj(o.partner);
  const stat = obj(o.stat);
  const ribbon = obj(o.ribbon);
  const logoPath = typeof partner.logo_path === "string" && partner.logo_path.trim() ? partner.logo_path.trim() : null;
  if (logoPath && !PARTNER_LOGO.test(logoPath)) return { ok: false, error: "The partner logo is not one uploaded here. Upload it again." };
  const rawRows = Array.isArray(o.agenda) ? o.agenda : [];
  if (rawRows.length > POSTER_AGENDA_MAX) return { ok: false, error: `The agenda has room for ${POSTER_AGENDA_MAX} rows.` };
  const agenda: PosterAgendaRow[] = [];
  for (const r of rawRows) {
    const row = obj(r);
    const time = cleanLine(row.time);
    const text = cleanLine(row.text);
    if (!time && !text) continue;
    agenda.push({ icon: isPosterIcon(row.icon) ? row.icon : "clock", time, text });
  }
  const poster: PosterContent = {
    occasion,
    frame: frame.value,
    scene: scene.value,
    logo: o.logo !== false,
    partner: { on: partner.on === true, label: cleanLine(partner.label), sub: cleanLine(partner.sub), logo_path: logoPath },
    subhead: cleanLine(o.subhead),
    slogan: cleanLine(o.slogan),
    stat: {
      on: stat.on === true,
      icon: isPosterIcon(stat.icon) ? stat.icon : "people",
      label: cleanLine(stat.label),
      value: cleanLine(stat.value),
      caption: cleanLine(stat.caption),
    },
    ribbon: { on: ribbon.on !== false, date: cleanLine(ribbon.date), time: cleanLine(ribbon.time) },
    agenda,
    paragraph: cleanLine(o.paragraph),
    footer: cleanLine(o.footer),
  };
  const checks: [keyof typeof POSTER_LIMITS, string][] = [
    ["subhead", poster.subhead],
    ["slogan", poster.slogan],
    ["partner_label", poster.partner.label],
    ["partner_sub", poster.partner.sub],
    ["stat_label", poster.stat.label],
    ["stat_value", poster.stat.value],
    ["stat_caption", poster.stat.caption],
    ["ribbon_date", poster.ribbon.date],
    ["ribbon_time", poster.ribbon.time],
    ["paragraph", poster.paragraph],
    ["footer", poster.footer],
    ...poster.agenda.flatMap((r): [keyof typeof POSTER_LIMITS, string][] => [
      ["agenda_time", r.time],
      ["agenda_text", r.text],
    ]),
  ];
  for (const [key, value] of checks) {
    if (flyerTextLength(value) > POSTER_LIMITS[key]) return { ok: false, error: `The ${POSTER_FIELD_LABEL[key]} is longer than ${POSTER_LIMITS[key]} characters.` };
  }
  if (poster.stat.on && !poster.stat.value) return { ok: false, error: "The highlight needs its big number (or switch the highlight off)." };
  return { ok: true, poster };
}

/** Every AI layer the poster uses belongs to this community (checked again on the server before it is drawn). */
export function posterLayersBelongTo(poster: PosterContent, centerId: string): boolean {
  return FLYER_LAYER_KINDS.every((k) => {
    const l = poster[k];
    return l.source !== "ai" || isCenterArtPath(l.path, centerId, poster.occasion, k);
  });
}

function parseBackground(raw: unknown): { ok: true; value: FlyerBackground } | { ok: false; error: string } {
  const o = raw && typeof raw === "object" && !Array.isArray(raw) ? (raw as Record<string, unknown>) : null;
  const source = o?.source;
  if (source === "pattern") {
    const p = o?.pattern;
    if (typeof p === "string" && (FLYER_PATTERNS as readonly string[]).includes(p)) return { ok: true, value: { source, pattern: p as FlyerPattern } };
    return { ok: false, error: "Choose one of the patterns: lotus, rangoli, diya or mandala." };
  }
  if (source === "photo") {
    const id = o?.photo_id;
    if (typeof id === "string" && UUID.test(id)) return { ok: true, value: { source, photo_id: id.toLowerCase() } };
    return { ok: false, error: "Choose a photo from one of the albums." };
  }
  if (source === "ai") {
    const path = typeof o?.path === "string" ? o.path.trim() : "";
    if (!ART_PATH.test(path)) return { ok: false, error: "Generate the AI art first, or choose another background." };
    const prompt = typeof o?.prompt === "string" ? o.prompt.trim().slice(0, 2000) : "";
    return { ok: true, value: { source, path, prompt } };
  }
  if (source === "plain") return { ok: true, value: { source } };
  return { ok: false, error: "Choose a background: a pattern, a photo, AI art or a plain colour." };
}

/** A flyer design from the client or the database, checked; every error is a plain sentence for the organizer. */
export function parseFlyerDesign(raw: unknown): { ok: true; design: FlyerDesign } | { ok: false; error: string } {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return { ok: false, error: "The flyer design is missing. Reload the page and try again." };
  const o = raw as Record<string, unknown>;
  if (o.v !== undefined && o.v !== 1) return { ok: false, error: "This flyer design was saved by a newer version of the flyer maker. Reload the page." };
  const template = o.template;
  if (typeof template !== "string" || !(FLYER_TEMPLATES as readonly string[]).includes(template)) {
    return { ok: false, error: "Choose a template: Poster, Classic, Festival, Minimal or Photo." };
  }
  const size = o.size;
  if (typeof size !== "string" || !(FLYER_SIZE_KEYS as readonly string[]).includes(size)) {
    return { ok: false, error: "Choose a size: Post, Tall, Story or Print." };
  }
  const text = {
    headline: cleanLine(o.headline),
    tagline: cleanLine(o.tagline),
    date_line: cleanLine(o.date_line),
    venue_line: cleanLine(o.venue_line),
  };
  if (!text.headline) return { ok: false, error: "The headline is required." };
  for (const key of Object.keys(FLYER_LIMITS) as (keyof typeof FLYER_LIMITS)[]) {
    if (flyerTextLength(text[key]) > FLYER_LIMITS[key]) {
      const label = FIELD_LABEL[key];
      return { ok: false, error: `The ${label} is longer than ${FLYER_LIMITS[key]} characters.` };
    }
  }
  const bg = parseBackground(o.background);
  if (!bg.ok) return bg;
  if (template === "photo" && bg.value.source !== "photo" && bg.value.source !== "ai") {
    return { ok: false, error: "The Photo template needs a photo or AI art background." };
  }
  // The poster's content is checked strictly when the Poster is the template; otherwise it is only kept when it is valid.
  let poster: PosterContent | undefined;
  if (template === "poster" || o.poster !== undefined) {
    const p = parsePosterContent(o.poster);
    if (p.ok) poster = p.poster;
    else if (template === "poster") return p;
  }
  return {
    ok: true,
    design: {
      v: 1,
      template: template as FlyerTemplate,
      size: size as FlyerSize,
      ...text,
      show_qr: o.show_qr === true,
      background: bg.value,
      ...(poster ? { poster } : {}),
    },
  };
}

