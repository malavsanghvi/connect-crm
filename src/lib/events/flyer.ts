// Event flyers — the flyer maker's pure parts (no server imports: the flyer
// panel is a client component and imports this file).
//
// A flyer is DESIGNED from the brand kit (owner decisions 2026-10-01): a
// template, a size, the words (headline, tagline, date line, venue line), an
// RSVP QR code, and one background — a pattern drawn in code, a photo from the
// community's approved albums, free AI background art, or a plain colour. The
// design is stored on the event as events.flyer_design (v1, migration 0578)
// and rendered server-side to a PNG (src/lib/events/flyer-render.tsx).
//
// AI art is art only: no text, letters, deities, idols or murtis, and no
// people up close. FLYER_ART_BLOCKED_TERMS and the two guardrails below are an
// exact copy of worker/src/flyer-guard.ts (tests/events-flyer.test.ts keeps
// them equal), so the portal refuses what the worker would refuse, before asking.
//
// Flyers v2 (owner decision 2026-10-02, approach C) adds the POSTER template:
// our layout and every word set by code (src/lib/events/flyer-poster.tsx) over
// an occasion art pack — a frame and a bottom scene drawn in code, or cached
// text-free AI art (src/lib/events/flyer-art.ts). Its content is stored in the
// same events.flyer_design, as `poster` (still v1: the field is optional, so
// every design saved before stays valid).

