export type PosterAgendaRow = { icon: PosterIcon; time: string; text: string };

/**
 * Everything the Poster template draws besides the headline (design.headline),
 * the venue (design.venue_line) and the QR code (design.show_qr). Every
 * section is optional: an empty or switched-off section is left out and the
 * rest of the poster closes up.
 */
export type PosterContent = {
  occasion: FlyerOccasion;
  frame: FlyerLayer;
  scene: FlyerLayer;
  /** The community's logo (brand kit) at the top. */
  logo: boolean;
  /** A partner's logo beside it: an uploaded PNG/JPEG, or a badge drawn from two short lines. */
  partner: { on: boolean; label: string; sub: string; logo_path: string | null };
  subhead: string;
  slogan: string;
  stat: { on: boolean; icon: PosterIcon; label: string; value: string; caption: string };
  /** The date ribbon: date and time lines (from the event by default) and the venue line. */
  ribbon: { on: boolean; date: string; time: string };
  /** 0 to 5 rows; none leaves the agenda out. */
  agenda: PosterAgendaRow[];
  paragraph: string;
  /** The footer band's line; empty shows the community's name. */
  footer: string;
};

